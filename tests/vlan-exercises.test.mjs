test(`bounded generation regression: ${full ? '12 seeds' : 'witness seeds'} per shape/vendor/level and task/syntax`, () => {
  const result = sweep(12, { sample: !full });
  // Independent contract: never derive expected combinations from the banks or
  // sweep rows. A removed/duplicated combination or seed must fail this gate.
  const all = Array.from({ length: 12 }, (_, i) => i);
  const base = all.slice(0, Number(process.env.NETGYM_TEST_SEEDS ?? 2));
  const expected = new Map();
  const add = (key, required) => expected.set(key,
    full ? all : [...new Set([...base, ...required])].sort((a, b) => a - b));
  const predictSeeds = {
    'p1/cisco': [[0, 1], [0, 1], [0, 1]],
    'p1/routeros': [[0, 1], [0, 1, 3], [0, 1]],
    'p2/cisco': [[0, 1], [0, 1], [0, 1]],
    'p2/routeros': [[0, 1], [0, 1, 2, 5], [0, 1, 3]],
    'p3/cisco': [[0, 1], [0, 1, 3], [0, 1]],
    'p3/routeros': [[0, 1], [0, 1, 3], [0, 1]],
  };
  for (const [key, levels] of Object.entries(predictSeeds)) {
    levels.forEach((seeds, level) => add(`predict/${key}/${level}`, seeds));
  }
  for (const id of [1, 2, 3, 4]) for (const syntax of ['cisco', 'routeros']) {
    add(`vlan.ports-${id}/${syntax}`, [0, 1]);
  }
  for (const key of ['1/cisco', '1/routeros', '2/cisco', '2/routeros', '3/cisco', '3/routeros', '4/routeros']) {
    add(`vlan.route-${key}`, [0, 1, 4]);
  }
  const rowKey = r => r.shape ? `predict/${r.shape}/${r.vendor}/${r.surprises}` : `${r.task}/${r.syntax}`;
  assert.deepEqual(result.rows.map(rowKey).sort(), [...expected.keys()].sort());
  for (const row of result.rows) {
    const key = rowKey(row), seeds = expected.get(key);
    assert.deepEqual([...row.seeds].sort((a, b) => a - b), seeds, key);
    assert.equal(row.instances, seeds.length, key);
  }
  const totals = [result.predictInstances, result.portsInstances, result.routeInstances];
  if (full) assert.deepEqual(totals, [216, 96, 84]);
  else if (base.length === 2) assert.deepEqual(totals, [42, 16, 21]);
  else assert.deepEqual(totals, ['predict/', 'vlan.ports-', 'vlan.route-'].map(prefix =>
    [...expected].filter(([key]) => key.startsWith(prefix)).reduce((n, [, seeds]) => n + seeds.length, 0)));
});

