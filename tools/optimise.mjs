import * as bank from '../src/banks/routing/tasks.js';
import { writeFile } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
import { tasks } from '../src/banks/routing/tasks.js';
import { create } from '../src/sections/routing/logic/static.js';
import { optimise, optimiserVersion } from '../src/sections/routing/logic/optimise.js';
import { optimiserHash } from './optimiser-hash.mjs';

const start = performance.now(), results = {};
for (const record of tasks) for (const variant of record.variants) {
  const task = create(record, { variantId: variant.id, bank });
  results[`${record.id}/${variant.id}`] = optimise(task);
}
const frozen = { version: optimiserVersion, hash: optimiserHash(), results };
await writeFile(new URL('../src/banks/routing/optimiser-results.json', import.meta.url), `${JSON.stringify(frozen, null, 2)}\n`);
// Pinned esbuild 0.15 cannot parse Node 24's JSON import attributes. Keep an
// executable mirror for browser/Node consumers, tested against the JSON source.
await writeFile(new URL('../src/banks/routing/optimiser-results.js', import.meta.url), `// Generated by tools/optimise.mjs; do not edit. See optimiser-results.json.\nexport default ${JSON.stringify(frozen)};\n`);
console.log(`Optimised ${Object.keys(results).length} variants in ${((performance.now() - start) / 1000).toFixed(3)} s`);
for (const [key, result] of Object.entries(results)) console.log(`${key}: ${result.referenceTotal} → ${result.total} (${JSON.stringify(result.counts)})`);
