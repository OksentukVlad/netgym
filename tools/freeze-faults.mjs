export function sourceHash() {
  const hash = createHash('sha256');
  for (const path of sources) hash.update(path).update('\0').update(readFileSync(new URL(`../${path}`, import.meta.url))).update('\0');
  return hash.digest('hex');
}

export function entryFor(task, analysis) {
  // Reserve low bits through the largest subnet or increment carry. XOR of
  // the remaining bits then commutes with dst + blockSize for EVERY site.
  const poolBits = privatePools.map(p => 32 - p.prefix);
  const preservedBits = privatePools.map(() => 0);
  const reserve = (ip, bits) => {
    const pool = privatePools.findIndex(p => contains(p.dst, p.prefix, ip));
    if (pool >= 0) preservedBits[pool] = Math.max(preservedBits[pool], bits);
  };
  for (const unit of task.record.generation.units) reserve(unit.mapped, 32 - unit.prefix);
  for (const device of task.network.devices) for (const iface of device.interfaces)
    if (iface.address) reserve(iface.address.ip, 32 - iface.address.prefix);
  for (const candidate of analysis.candidates) {
    const site = candidate.site, row = analysis.baseline[site.router][site.index];
    if (row.prefix) reserve(row.dst, 32 - row.prefix);
    if (site.code === 'wrong-destination') {
      if (!privatePools.some(p => contains(p.dst, p.prefix, row.dst) && contains(p.dst, p.prefix, site.changed)))
        throw new Error('Planting crosses a pool boundary');
      reserve(row.dst, 32 - Math.clz32((toInt(row.dst) ^ toInt(site.changed)) >>> 0));
    }
  }
  return { units: task.record.generation.units,
    masks: poolBits.map((bits, index) => ((2 ** bits - 1) & ~((2 ** preservedBits[index]) - 1)) >>> 0),
    candidates: analysis.candidates.map(({ site, gates, visible, valid, ambiguousWith, accepted, observation }) =>
      ({ key: site.key, gates, visible, valid, ambiguousWith, accepted, observation })) };
}

export function generate() {
  const results = {};
  for (const definition of record.variants) {
    const source = bank.tasks.find(t => t.id === definition.taskId);
    const task = create(source, { bank, seed: 0, variantId: definition.variantId });
    if (task.infeasible) throw new Error(`Infeasible template: ${source.id}`);
    results[`${source.id}/${definition.variantId}`] = entryFor(task, analyse(task));
  }
  return { tableVersion, generatorVersion, sourceHash: sourceHash(), inputs: JSON.stringify(frozenInputs(record, bank)), results };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const data = generate();
  writeFileSync(new URL('../src/banks/routing/faults-results.json', import.meta.url), `${JSON.stringify(data, null, 2)}\n`);
  writeFileSync(new URL('../src/banks/routing/faults-results.js', import.meta.url), `// Generated by tools/freeze-faults.mjs; do not edit.\nexport default ${JSON.stringify(data)};\n`);
  console.log(`Frozen ${Object.keys(data.results).length} variants, ${Object.values(data.results).reduce((n,e)=>n+e.candidates.length,0)} sites.`);
}
